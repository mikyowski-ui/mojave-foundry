/// The rows of the glyph that draws `c`: its own for printable ASCII and
/// `'…'`, [`FALLBACK`] for everything else (control characters included).
pub fn glyph(c: char) -> [u8; 7] {
    match c {
        ' '..='~' => ASCII[c as usize - 0x20],
        ELLIPSIS => ELLIPSIS_GLYPH,
        _ => FALLBACK,
    }
}

/// Width in pixels of `text` drawn at `scale`: one [`ADVANCE`] per
/// character, without the spacing column after the last one.
pub fn text_width(text: &str, scale: u32) -> u32 {
    let count = u32::try_from(text.chars().count()).unwrap_or(u32::MAX);
    if count == 0 {
        return 0;
    }
    count
        .saturating_mul(ADVANCE)
        .saturating_sub(1)
        .saturating_mul(scale)
}

/// Height in pixels of one line of text at `scale`, spacing included.
pub fn line_height(scale: u32) -> u32 {
    LINE_HEIGHT.saturating_mul(scale)
}

/// `text` when it fits in `max_width` pixels at `scale`, otherwise its
/// longest prefix that fits followed by `'…'`. Empty when not even the
/// ellipsis fits.
pub fn truncate_to_width(text: &str, max_width: u32, scale: u32) -> String {
    if text_width(text, scale) <= max_width {
        return text.to_owned();
    }
    let mut out = String::new();
    let mut kept = 0u32;
    for c in text.chars() {
        // Width of `kept + 1` characters plus the ellipsis.
        let candidate = (kept + 2)
            .saturating_mul(ADVANCE)
            .saturating_sub(1)
            .saturating_mul(scale);
        if candidate > max_width {
            break;
        }
        out.push(c);
        kept += 1;
    }
    let ellipsis_only = (ADVANCE - 1).saturating_mul(scale);
    if kept == 0 && ellipsis_only > max_width {
        return String::new();
    }
    out.push(ELLIPSIS);
    out
}

/// Draws `text` with its top-left corner at (`x`, `y`), each font pixel a
/// `scale` x `scale` block of `colour` alpha-blended over the target.
/// Pixels outside the canvas are clipped. Returns the drawn width
/// ([`text_width`]). A `scale` of 0 draws nothing.
pub fn draw_text(
    target: &mut Canvas<'_>,
    x: i32,
    y: i32,
    text: &str,
    colour: [u8; 4],
    scale: u32,
) -> u32 {
    if scale == 0 {
        return 0;
    }
    let step = i64::from(ADVANCE) * i64::from(scale);
    let scale_i = i64::from(scale);
    let mut pen = i64::from(x);
    for c in text.chars() {
        // Stop once the pen is past the right edge: nothing more is visible.
        if pen >= i64::from(target.width()) {
            break;
        }
        let rows = glyph(c);
        for (row, bits) in rows.iter().enumerate() {
            for column in 0..GLYPH_WIDTH {
                if bits & (0x10 >> column) == 0 {
                    continue;
                }
                let px = pen + i64::from(column) * scale_i;
                let py = i64::from(y) + row as i64 * scale_i;
                target.blend_rect_i64(px, py, scale_i, scale_i, colour);
            }
        }
        pen += step;
    }
    text_width(text, scale)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_glyph_but_space_has_ink() {
        for c in ' '..='~' {
            let rows = glyph(c);
            let ink = rows.iter().any(|row| *row != 0);
            assert_eq!(ink, c != ' ', "glyph {c:?}");
            assert!(rows.iter().all(|row| *row < 0x20), "glyph {c:?} is 5 wide");
        }
    }

    #[test]
    fn printable_glyphs_are_distinct() {
        let mut seen: Vec<[u8; 7]> = (' '..='~').map(glyph).collect();
        seen.push(FALLBACK);
        seen.push(ELLIPSIS_GLYPH);
        let count = seen.len();
        seen.sort_unstable();
        seen.dedup();
        assert_eq!(seen.len(), count);
    }

    #[test]
    fn fallback_covers_everything_else() {
        assert_eq!(glyph('\n'), FALLBACK);
        assert_eq!(glyph('\u{7f}'), FALLBACK);
        assert_eq!(glyph('é'), FALLBACK);
        assert_ne!(glyph(ELLIPSIS), FALLBACK);
    }

    #[test]
    fn widths() {
        assert_eq!(text_width("", 1), 0);
        assert_eq!(text_width("A", 1), 5);
        assert_eq!(text_width("AB", 1), 11);
        assert_eq!(text_width("AB", 3), 33);
        assert_eq!(line_height(2), 18);
    }

    #[test]
    fn truncation() {
        assert_eq!(truncate_to_width("short", 100, 1), "short");
        assert_eq!(truncate_to_width("abcdef", 35, 1), "abcdef"); // 35 px exactly
        // 4 characters fit with the ellipsis in 29 px: 5 x 6 - 1.
        assert_eq!(truncate_to_width("abcdefgh", 29, 1), "abcd…");
        assert!(text_width(&truncate_to_width("abcdefgh", 29, 1), 1) <= 29);
        assert_eq!(truncate_to_width("abcdefgh", 28, 1), "abc…");
        assert_eq!(truncate_to_width("abcdefgh", 5, 1), "…");
        assert_eq!(truncate_to_width("abcdefgh", 4, 1), "");
        // At scale 2, "a…" is 22 px wide.
        assert_eq!(truncate_to_width("abcdefgh", 22, 2), "a…");
    }
}
