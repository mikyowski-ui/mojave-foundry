//! A fixed-width 5 x 7 bitmap font in a 6 x 9 cell, drawn for this crate.
//!
//! Each glyph is seven rows of five bits; bit 4 (`0x10`) is the leftmost
//! column. Printable ASCII (`' '` to `'~'`) and the ellipsis `'…'` have
//! glyphs; every other character draws [`FALLBACK`], a crossed box.

use crate::canvas::Canvas;

/// Glyph width in font pixels.
pub const GLYPH_WIDTH: u32 = 5;
/// Glyph height in font pixels.
pub const GLYPH_HEIGHT: u32 = 7;
/// Horizontal advance per character in font pixels (glyph plus one column).
pub const ADVANCE: u32 = 6;
/// Line height in font pixels (glyph plus two rows).
pub const LINE_HEIGHT: u32 = 9;
/// The character [`truncate_to_width`] appends.
pub const ELLIPSIS: char = '…';

