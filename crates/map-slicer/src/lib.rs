//! Per-hex wall and scenery strip slicing and the FID budget tracker.
//!
//! [`slice_statics`] takes the static references placed in one map window
//! and decides what each becomes ([`classify`]):
//!
//! - **skipped**: deleted, disabled (also through an enable parent), not
//!   scenery, without a mesh, an effect or marker by its model path, or an
//!   empty render;
//! - **ground flat**: under `flat_height` tall (roads, decals), flattened
//!   onto the floor and returned as an RGBA overlay in map screen space;
//! - **ground relief**: rocks and cliffs by model path, or anything above
//!   `max_sliced_hexes` of floor; rendered in full relief as an overlay,
//!   the hexes under it returned in `blocked_hexes`. Relief is floor art:
//!   it never occludes a character. That is an accepted limit of this pass;
//! - **sprite**: items, doors, containers, vegetation by model path,
//!   scenery of at most `sprite_max_hexes` of floor, and sparse meshes
//!   (wires spanning a huge box: triangle area under `sparse_ratio` of the
//!   footprint); one art entry, placed at the hex under its origin with the
//!   sub-hex offset in the placement's displacement;
//! - **sliced**: everything else (buildings, fences, large props), cut into
//!   per-hex strips in the walls list.
//!
//! Defaults (tuned on a real desert town window, about 1,350 references):
//! flat under 35 units; sprites up to 2 hexes and 150 units long; relief
//! above 2,500 hexes; sparse below 0.15; strips under 48 pixels merged;
//! interior row runs merged whole, perimeter row runs in threes.
//!
//! # Map screen space and anchoring
//!
//! Contracts section 9: map screen space is `HexGrid::default()`. Every
//! render is canonical: the mesh is rendered with its rotation and scale
//! but no translation, so its origin projects to screen `(0, 0)`. The
//! reference's own ground point (its origin dropped to the terrain under
//! it) is projected into map screen space and rounded to a pixel, `G`; its
//! height above that terrain is rounded to pixels, `H`. The object is drawn
//! with its canonical pixel `(0, 0)` at `G - (0, H)`. So two references that
//! differ only by a whole-hex translation produce the same pixels at the
//! same offsets from their hexes, and share their art. On this lattice a
//! whole-hex translation is a screen step generated by `(48, -12)` (two
//! columns, one floor square east) and `(16, 12)` (one row, half a square
//! south). A single column is `(32, 0)` or `(16, -12)` depending on its
//! parity: it maps hexes to hexes and pixel ownership with them, but it
//! re-pairs the zig-zag hex rows, so interior runs and tie-breaks between
//! equally near strips may come out differently. Renders are
//! cached by (mesh, rotation, scale); the sub-hex phase only decides which
//! hex owns which pixel, which is recomputed per reference, and equal
//! strips are then shared by content hash. The height `H` never reaches
//! the art: it is carried in each placement's displacement.
//!
//! # Strips
//!
//! Each opaque pixel belongs to the hex its surface point (found through
//! the depth buffer) stands over. Pixels off the map are dropped and
//! counted; pixels outside the object's footprint (eaves) stay with their
//! hex, whose strip then does not block. Strips under `min_strip_pixels`
//! join the nearest larger strip of the object. Consecutive hexes of one
//! hex row that the object blocks merge into one strip anchored at the
//! middle hex (`Placement::run`): interior runs (under a roof) whole,
//! perimeter runs in pieces of `max_perimeter_run`; the run's other hexes
//! go to `blocked_hexes`. Under the engine's row-major draw order this
//! changes no occlusion against anything outside the run. Roofs stay
//! strips of the hexes under them in this pass. The engine draws objects in ascending
//! hex number (row-major); a strip nearer the viewer than another it
//! overlaps on screen always has the larger hex number, so strips draw back
//! to front. Recomposing every strip at its hex reproduces the object's
//! render exactly.
//!
//! # Budget
//!
//! Art is deduplicated over the whole run by content (category, size,
//! shift, pixels). [`Sliced::report`] carries the accounting; a demand above
//! [`Budget`] is [`SliceError::FidBudget`]. [`estimate`] classifies and
//! counts footprints without rendering, as a fast pre-check.

