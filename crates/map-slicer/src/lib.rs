/// The art lists the slicer fills.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ArtCategory {
    Walls,
    Scenery,
    Items,
}

impl ArtCategory {
    pub const ALL: [ArtCategory; 3] =
        [ArtCategory::Walls, ArtCategory::Scenery, ArtCategory::Items];

    /// The art directory: `walls`, `scenery`, `items`.
    pub fn name(self) -> &'static str {
        match self {
            ArtCategory::Walls => "walls",
            ArtCategory::Scenery => "scenery",
            ArtCategory::Items => "items",
        }
    }

    pub(crate) fn index(self) -> usize {
        match self {
            ArtCategory::Walls => 0,
            ArtCategory::Scenery => 1,
            ArtCategory::Items => 2,
        }
    }
}

/// What a placed object is to the map builder.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Role {
    /// One strip of a sliced object (walls list).
    WallStrip,
    /// A scenery sprite.
    Scenery,
    /// A door (scenery list).
    Door,
    /// A container. Fallout 2 containers are item prototypes, so their art
    /// is in the items list.
    Container,
    /// A carried item lying on the map (items list).
    Item,
    /// A walking surface of a sliced object above the terrain, such as a
    /// porch floor (scenery list). The builder places it flat, never
    /// blocking and never cut by the see-through circle, so whoever stands
    /// on it stands on planks, not on the terrain under them.
    FloorPiece,
}

/// One art entry: a single-frame, single-direction FRM's content.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ArtImage {
    pub category: ArtCategory,
    pub width: u32,
    pub height: u32,
    /// Indexed, row-major, index 0 transparent.
    pub pixels: Vec<u8>,
    /// The FRM direction shift (`emit::sprite_shift`).
    pub shift: [i16; 2],
    /// The model path of the first reference that produced it.
    pub source: String,
}

/// One object to place.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Placement {
    /// Index into [`Sliced::art`].
    pub art: usize,
    /// The hex the engine anchors it at.
    pub hex: i32,
    /// The object's own pixel offset, added after the FRM shift: the
    /// sub-hex position of a sprite, the height above the terrain of a
    /// strip.
    pub displacement: [i32; 2],
    pub role: Role,
    /// The reference's form key.
    pub reference: String,
    pub blocking: bool,
    /// For a strip that is a merged interior run: the first and last hex of
    /// the run, in the same row as `hex`. The run's other hexes are listed
    /// in [`Sliced::blocked_hexes`].
    pub run: Option<(i32, i32)>,
}

/// An RGBA8 image in map screen space, to composite into the floor.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BakedOverlay {
    /// Map screen position of pixel (0, 0).
    pub origin: [i32; 2],
    pub width: u32,
    pub height: u32,
    pub rgba: Vec<u8>,
}

/// A reference that produced nothing, and why.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Skipped {
    /// The reference's form key.
    pub reference: String,
    pub model: Option<String>,
    pub reason: SkipReason,
}

/// Everything a run produced.
#[derive(Debug, Clone, PartialEq)]
pub struct Sliced {
    /// Distinct art, in order of first use.
    pub art: Vec<ArtImage>,
    /// Sorted by hex (the engine's draw order), then reference, then art.
    pub placements: Vec<Placement>,
    /// Flat overlays first, then relief; composite in this order.
    pub overlays: Vec<BakedOverlay>,
    /// Hexes to block without an object of their own: under relief, and
    /// the non-anchor hexes of merged interior runs. Sorted.
    pub blocked_hexes: Vec<i32>,
    /// Sorted by reference.
    pub skipped: Vec<Skipped>,
    pub report: BudgetReport,
}
